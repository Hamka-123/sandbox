#!/bin/bash

# =================================================================
# ШПАРГАЛКА ПО СИНТАКСИСУ BASH
# =================================================================

# 1. ПЕРЕМЕННЫЕ
NAME="Gemini"       # Присваивание: БЕЗ пробелов вокруг "="
readonly PI=3.14    # Константа
unset NAME          # Удаление переменной

# 2. ТИПЫ КАВЫЧЕК
VAR="Мир"
echo "Привет, $VAR" # Двойные: переменные раскрываются (Привет, Мир)
echo 'Привет, $VAR' # Одинарные: текст "как есть" (Привет, $VAR)
echo $(date)        # Обратные кавычки или $(): выполнение команды

# 3. АРГУМЕНТЫ СКРИПТА (запуск: ./script.sh arg1 arg2)
echo "Имя скрипта: $0"
echo "Первый аргумент: $1"
echo "Всего аргументов: $#"
echo "Все аргументы: $@"

# 4. УСЛОВИЯ (Числа)
# -eq (равно), -ne (не равно), -lt (<), -le (<=), -gt (>), -ge (>=)
if [[ $1 -gt 10 ]]; then
    echo "Число больше 10"
elif [[ $1 -eq 10 ]]; then
    echo "Число равно 10"
else
    echo "Число меньше 10"
fi

# 5. УСЛОВИЯ (Строки и Файлы)
# == (равно), != (не равно), -z (пустая строка)
# -e (файл существует), -d (папка), -f (обычный файл)
if [[ -f "/etc/passwd" ]]; then
    echo "Файл паролей на месте"
fi

# 6. ЦИКЛЫ
# Цикл по списку
for FRUIT in apple banana cherry; do
    echo "Я люблю $FRUIT"
done

# Цикл от 1 до 5
for i in {1..5}; do
    echo "Счетчик: $i"
done

# Цикл while
count=0
while [[ $count -lt 3 ]]; do
    echo "Шаг $count"
    ((count++)) # Арифметическая операция
done

# 7. ФУНКЦИИ
my_function() {
    local func_param=$1 # local ограничивает видимость переменной
    echo "Функция получила: $func_param"
    return 0 # Код возврата (0-255)
}

my_function "Работает!"

# 8. ПЕРЕНАПРАВЛЕНИЯ
# >  (записать в файл, затереть старое)
# >> (добавить в конец файла)
# 2> (перенаправить только ошибки)
# &> (перенаправить и вывод, и ошибки)

ls /nonexistent &> /dev/null # "Тихий" режим: всё в "черную дыру"

# 9. ЛОГИЧЕСКИЕ СВЯЗКИ
# && — выполнить второе, только если первое успешно
# || — выполнить второе, только если первое провалилось
# | - пайплайн
mkdir my_folder && cd my_folder