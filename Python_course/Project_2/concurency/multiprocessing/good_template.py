import multiprocessing as mp


# ---------------------------
# 1. Все вызываемые функции — только на уровне модуля!
# ---------------------------
def worker(x):
    # Внутри можно использовать лямбды, вложенные функции, всё что угодно,
    # главное — НЕ возвращать наружу несериализуемые объекты.
    transform = lambda v: v * 2
    return transform(x)


# ---------------------------
# 2. Фабрика для пула/процессов
# (чтобы можно было менять стартовый метод централизованно)
# ---------------------------
def create_pool(processes=None):
    # если важно явно — можно задать spawn/fork:
    # mp.set_start_method("spawn", force=True)

    return mp.Pool(processes or mp.cpu_count())


# ---------------------------
# 3. Основной entrypoint — защищён проверкой __main__
# ---------------------------
def main():
    with create_pool() as pool:
        results = pool.map(worker, [1, 2, 3, 4])
    print("Results:", results)


# ---------------------------
# 4. Запуск только через __main__
# ---------------------------
if __name__ == "__main__":
    main()

"""
    | Правило                                          | Причина                          |
| ------------------------------------------------ | -------------------------------- |
| Все target-функции → на уровне модуля            | spawn требует pickle             |
| Весь запуск → под `if __name__ == "__main__"`    | избежать рекурсивного старта     |
| Не передавать в процессы несериализуемые объекты | лямбды/замыкания/файлы ломаются  |
| Внутри worker() можно делать всё                 | тело функции не сериализуется    |
| Закрывать процессы контекст-менеджером           | отсутствие утечек ресурсов       |
| Настраивать стартовый метод централизованно      | одинаковое поведение на системах |

"""