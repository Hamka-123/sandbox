# =============================================================================
# 4. БИТОВЫЕ ОПЕРАЦИИ
# =============================================================================

x = 0b1100  # 12
y = 0b1010  # 10

# AND (&) - общие биты
and_result = x & y  # 0b1000 = 8

# OR (|) - любой из битов
or_result = x | y   # 0b1110 = 14

# XOR (^) - исключающее ИЛИ
xor_result = x ^ y  # 0b0110 = 6

# NOT (~) - инвертирование битов
not_result = ~x     # -13 (в дополнительном коде)

# Сдвиги:
left_shift = x << 2   # 0b110000 = 48 (умножение на 4)
right_shift = x >> 1  # 0b0110 = 6 (деление на 2)

# 💡 Важно: Сдвиг вправо сохраняет знак для отрицательных чисел!

# =============================================================================
# 5. РАБОТА С ОТДЕЛЬНЫМИ БИТАМИ
# =============================================================================

def set_bit(value, bit_position):
    """Установить бит в 1"""
    return value | (1 << bit_position)

def clear_bit(value, bit_position):
    """Сбросить бит в 0"""
    return value & ~(1 << bit_position)

def toggle_bit(value, bit_position):
    """Переключить бит (0→1, 1→0)"""
    return value ^ (1 << bit_position)

def check_bit(value, bit_position):
    """Проверить установлен ли бит"""
    return (value >> bit_position) & 1

# 💡 Важно: Биты нумеруются справа налево (0 - младший бит)

