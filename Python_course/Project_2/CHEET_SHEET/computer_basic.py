# Эффективное хранение множества boolean значений
READ_PERMISSION = 0b001  # 1
WRITE_PERMISSION = 0b010 # 2  
EXECUTE_PERMISSION = 0b100 # 4

user_permissions = READ_PERMISSION | WRITE_PERMISSION  # 0b011

# Проверка прав:
can_read = user_permissions & READ_PERMISSION != 0
can_execute = user_permissions & EXECUTE_PERMISSION != 0

# Добавление прав:
user_permissions |= EXECUTE_PERMISSION

# Удаление прав:
user_permissions &= ~WRITE_PERMISSION

# 💡 Важно: Используйте степени двойки для флагов!

