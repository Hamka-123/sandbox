'''
# Шпаргалка по модулям и пакетам в Python (macOS, venv)

1. Проверка версии Python:
python --version      # версия Python из venv
python3 --version     # альтернативный способ

2. Список установленных пакетов:
pip list
# Выводит все пакеты с версиями, установленные в текущем виртуальном окружении.
# Фильтрация по имени:
pip list | grep requests

3. Список доступных модулей внутри Python:
import pkgutil

for module in pkgutil.iter_modules():
    print(module.name)
# Показывает все модули, которые Python может импортировать в текущей среде.
# Работает для стандартных модулей и установленных через pip.

4. Просмотр содержимого конкретного модуля:
import math
print(dir(math))
# Выводит список функций, переменных и атрибутов модуля.

5. Использование help() для модулей:
help('modules')
# Показывает все доступные модули в интерактивном Python.
# Может быть медленным, если установлено много пакетов.

6. Поиск информации о конкретном пакете:
pip show requests
# Показывает подробную информацию: версия, зависимости, путь установки.

7. Общие советы:
# - На macOS команда 'py' не работает, используйте 'python' или 'python3'.
# - В виртуальном окружении (venv) достаточно использовать 'python', он будет указывать на версию из venv.
# - Для динамического просмотра модулей и функций полезны функции dir(), pkgutil.iter_modules(), и модуль inspect.
'''
